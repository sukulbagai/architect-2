function pageComponent(page: PlanPage, plan: Plan, paths: { data: string; lib: string; components: string }) {
  const name = pascal(page.name);
  const c = plan.data.find((d) => d.id === page.collection) ?? plan.data[0];
  const agent = plan.agents.find((a) => a.id === page.agent) ?? plan.agents[0];
  const dataImport = c ? `import { ${camel(c.name)} } from "${paths.data}/${c.id}";\n` : "";
  const agentImport = agent ? `import { runAgent } from "${paths.lib}/agents";\n` : "";
  const header = `      <header className="page-header">
        <h1>${page.name}</h1>
        <p>${page.purpose}</p>
      </header>`;

  switch (page.kind) {
    case "dashboard": {
      const money = c?.fields.find((f) => f.type === "money");
      return `import { useMemo } from "react";
${dataImport}import { StatCard } from "${paths.components}/StatCard";
import { StatusPill } from "${paths.components}/StatusPill";

export default function ${name}() {
  const rows = ${c ? camel(c.name) : "[]"};
  const byStatus = useMemo(() => {
    const counts = new Map<string, number>();
    for (const row of rows) counts.set(${c?.statusField ? `row.${c.statusField}` : '"All"'}, (counts.get(${c?.statusField ? `row.${c.statusField}` : '"All"'}) ?? 0) + 1);
    return [...counts.entries()];
  }, [rows]);

  return (
    <div className="page">
${header}
      <section className="stats">
        <StatCard label="Total ${c?.name.toLowerCase() ?? "items"}" value={rows.length} />
${byStatus_tiles(c)}${money ? `        <StatCard label="Total ${money.label.toLowerCase()}" value={rows.reduce((sum, r) => sum + r.${money.key}, 0)} format="money" />\n` : ""}      </section>

      <section className="card">
        <h2>By ${c?.statusField ?? "status"}</h2>
        <ul className="bars">
          {byStatus.map(([status, count]) => (
            <li key={status}>
              <StatusPill value={status} />
              <span className="bar" style={{ width: \`\${(count / rows.length) * 100}%\` }} />
              <span>{count}</span>
            </li>
          ))}
        </ul>
      </section>
    </div>
  );
}
`;
    }
    case "list": {
      const cols = c?.fields.slice(0, 5) ?? [];
      return `import { useMemo, useState } from "react";
${dataImport}${agentImport}import { StatusPill } from "${paths.components}/StatusPill";

export default function ${name}() {
  const [query, setQuery] = useState("");
  const [selected, setSelected] = useState<string | null>(null);
  const [answer, setAnswer] = useState<string>("");

  const rows = useMemo(
    () =>
      ${c ? camel(c.name) : "[]"}.filter((row) =>
        Object.values(row).some((value) => String(value).toLowerCase().includes(query.toLowerCase())),
      ),
    [query],
  );

  async function ask(id: string) {
    setSelected(id);
    const row = rows.find((r) => r.id === id);
    ${agent ? `const run = await runAgent("${agent.id}", "Summarise this ${c?.singular.toLowerCase() ?? "item"} and suggest the next step.", { row });
    setAnswer(run.output);` : "setAnswer(JSON.stringify(row));"}
  }

  return (
    <div className="page">
${header}
${plan.ui.search ? `      <input className="search" placeholder="Search ${c?.name.toLowerCase() ?? "items"}" value={query} onChange={(e) => setQuery(e.target.value)} />\n` : ""}      <table className="card table">
        <thead>
          <tr>
${cols.map((f) => `            <th>${f.label}</th>`).join("\n")}
          </tr>
        </thead>
        <tbody>
          {rows.map((row) => (
            <tr key={row.id} onClick={() => ask(row.id)} aria-selected={selected === row.id}>
${cols.map((f) => (f.type === "status" ? `              <td><StatusPill value={row.${f.key}} /></td>` : `              <td>{row.${f.key}}</td>`)).join("\n")}
            </tr>
          ))}
        </tbody>
      </table>

      {answer && <aside className="card answer">{answer}</aside>}
    </div>
  );
}
`;
    }
    case "workbench":
      return `import { useState } from "react";
${dataImport}${agentImport}
export default function ${name}() {
  const items = ${c ? camel(c.name) : "[]"};
  const [current, setCurrent] = useState(items[0]);
  const [draft, setDraft] = useState("");
  const [busy, setBusy] = useState(false);

  async function generate() {
    setBusy(true);
    const run = await runAgent("${agent?.id ?? "assistant"}", "Draft a response for this ${c?.singular.toLowerCase() ?? "item"}.", { item: current });
    setDraft(run.output);
    setBusy(false);
  }

  return (
    <div className="page workbench">
${header}
      <nav className="card list">
        {items.map((item) => (
          <button key={item.id} onClick={() => setCurrent(item)} aria-current={item.id === current?.id}>
            {item.${c?.titleField ?? "id"}}
          </button>
        ))}
      </nav>
      <section className="card">
        <h2>{current?.${c?.titleField ?? "id"}}</h2>
        <button className="button" onClick={generate} disabled={busy}>
          {busy ? "${agent?.name ?? "Agent"} is writing…" : "Draft with ${agent?.name ?? "the agent"}"}
        </button>
        <textarea value={draft} onChange={(e) => setDraft(e.target.value)} rows={12} />
        <div className="actions">
          <button className="button">Approve</button>
          <button onClick={generate}>Regenerate</button>
        </div>
      </section>
    </div>
  );
}
`;
    case "chat":
      return `import { useState } from "react";
${agentImport}
type Message = { role: "user" | "agent"; text: string };

export default function ${name}() {
  const [messages, setMessages] = useState<Message[]>([
    { role: "agent", text: "Hi! I'm ${agent?.name ?? "your assistant"}. ${agent?.role ?? ""}" },
  ]);
  const [input, setInput] = useState("");

  async function send() {
    const text = input.trim();
    if (!text) return;
    setMessages((m) => [...m, { role: "user", text }]);
    setInput("");
    const run = await runAgent("${agent?.id ?? "assistant"}", text);
    setMessages((m) => [...m, { role: "agent", text: run.output }]);
  }

  return (
    <div className="page chat">
${header}
      <ol className="messages">
        {messages.map((m, i) => (
          <li key={i} className={m.role}>{m.text}</li>
        ))}
      </ol>
      <form onSubmit={(e) => { e.preventDefault(); send(); }}>
        <input value={input} onChange={(e) => setInput(e.target.value)} placeholder="Ask ${agent?.name ?? "the assistant"} anything…" />
        <button className="button">Send</button>
      </form>
    </div>
  );
}
`;
    case "run": {
      const pipeline = plan.agents.map((a) => `"${a.id}"`).join(", ");
      return `import { useState } from "react";
${agentImport}
const PIPELINE = [${pipeline}] as const;

export default function ${name}() {
  const [input, setInput] = useState("");
  const [step, setStep] = useState<number | null>(null);
  const [result, setResult] = useState("");

  async function run() {
    let context = input;
    for (let i = 0; i < PIPELINE.length; i++) {
      setStep(i);
      const out = await runAgent(PIPELINE[i], context);
      context = out.output;
    }
    setStep(null);
    setResult(context);
  }

  return (
    <div className="page">
${header}
      <label className="card field">
        <span>${page.input?.label ?? "Input"}</span>
        <textarea value={input} onChange={(e) => setInput(e.target.value)} placeholder="${page.input?.placeholder ?? ""}" rows={5} />
      </label>
      <button className="button" onClick={run} disabled={!input || step !== null}>
        {step === null ? "${page.input?.cta ?? "Run"}" : \`Running \${PIPELINE[step]}…\`}
      </button>
      {result && <article className="card result">{result}</article>}
    </div>
  );
}
`;
    }
    case "settings":
      return `const INTEGRATIONS = ${JSON.stringify(plan.integrations)};

export default function ${name}() {
  return (
    <div className="page">
${header}
      <section className="card">
        <h2>Connections</h2>
        <ul>
          {INTEGRATIONS.map((name) => (
            <li key={name}>
              {name} <button>Manage</button>
            </li>
          ))}
        </ul>
      </section>
      <section className="card">
        <h2>Notifications</h2>
        <label><input type="checkbox" defaultChecked /> Email me a daily summary</label>
        <label><input type="checkbox" /> Notify me when an agent needs approval</label>
      </section>
    </div>
  );
}
`;
  }
}

function byStatus_tiles(c?: PlanCollection) {
  if (!c?.statusField) return "";
  const first = String(c.rows[0]?.[c.statusField] ?? "");
  if (!first) return "";
  return `        <StatCard label="${first}" value={rows.filter((r) => r.${c.statusField} === "${first}").length} tone="accent" />\n`;
}

function statusPill() {
  return `const TONES: Record<string, string> = {
  urgent: "danger", high: "danger", overdue: "danger", exception: "danger", blocked: "danger", rejected: "danger",
  done: "success", paid: "success", sent: "success", mastered: "success", ok: "success", indexed: "success", clean: "success",
  "in progress": "warning", review: "warning", "needs review": "warning", learning: "warning", medium: "warning",
};

export function StatusPill({ value }: { value: string }) {
  const tone = TONES[value.toLowerCase()] ?? "neutral";
  return <span className={\`pill pill-\${tone}\`}>{value}</span>;
}
`;
}

function statCard() {
  return `const money = new Intl.NumberFormat("en-US", { style: "currency", currency: "USD", maximumFractionDigits: 0 });

export function StatCard({ label, value, format, tone }: { label: string; value: number; format?: "money"; tone?: "accent" }) {
  return (
    <div className={\`card stat \${tone ?? ""}\`}>
      <span>{label}</span>
      <strong>{format === "money" ? money.format(value) : value}</strong>
    </div>
  );
}
`;
}

