function dataFile(c: PlanCollection, importPath = "") {
  const typeName = pascal(c.singular);
  const fields = c.fields.map((f) => `  ${f.key}: ${tsType(f.type)};`).join("\n");
  const statusValues = c.statusField ? Array.from(new Set(c.rows.map((r) => String(r[c.statusField!])))).filter(Boolean) : [];
  return `${importPath}export type ${typeName} = {
  id: string;
${fields}
};
${
  statusValues.length
    ? `
export const ${camel(c.singular)}Statuses = ${JSON.stringify(statusValues)} as const;
`
    : ""
}
/** Sample ${c.name.toLowerCase()} so the app has something to show before real data arrives. */
export const ${camel(c.name)}: ${typeName}[] = ${json(c.rows.map((r, i) => ({ id: `${c.id}_${i + 1}`, ...r })))};
`;
}

function agentYaml(a: PlanAgent) {
  const tools = a.tools.length ? a.tools.map((t) => `  - ${t}`).join("\n") : "  []";
  return `# ${a.name} agent
name: ${a.name}
framework: ${a.framework}
model: ${a.model}
role: ${a.role}
instructions: |
  ${a.instructions.replace(/\n/g, "\n  ")}
tools:
${tools}
memory:
  type: conversation
  window: 20
guardrails:
  - Never send external messages without an approval step unless the plan says so.
  - Cite the source for any factual claim.
`;
}

function agentsClient(plan: Plan, endpoint: string) {
  const ids = plan.agents.map((a) => `"${a.id}"`).join(" | ") || "string";
  return `export type AgentId = ${ids};

export type AgentRun = {
  output: string;
  trace: { step: string; ms: number }[];
};

/**
 * Runs an agent on the server. Keys stay server-side; the browser only ever sees the output.
 */
export async function runAgent(agent: AgentId, input: string, context?: Record<string, unknown>): Promise<AgentRun> {
  const res = await fetch(\`${endpoint}\`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ input, context }),
  });
  if (!res.ok) throw new Error(\`Agent \${agent} failed: \${res.status}\`);
  return res.json();
}
`;
}

