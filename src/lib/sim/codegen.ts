/**
 * Turns a plan into the files of a small but real-looking project. Output is deterministic, so a
 * plan change regenerates exactly the files it affects and the version diff stays honest.
 */

export type Stack = "react-vite" | "nextjs" | "fastapi-react";

const pascal = (s: string) => {
  const p = s
    .replace(/[^a-zA-Z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");
  return /^[0-9]/.test(p) ? `Page${p}` : p || "Page";
};
const camel = (s: string) => {
  const p = pascal(s);
  return p[0].toLowerCase() + p.slice(1);
};
const json = (v: unknown) => JSON.stringify(v, null, 2);

function tsType(t: string) {
  return t === "number" || t === "money" ? "number" : "string";
}

