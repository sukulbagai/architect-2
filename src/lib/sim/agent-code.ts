function gitagent(a: PlanAgent, f: Framework, ctx: Ctx, dir: string): Record<string, string> {
  const specs = toolSpecs(a);
  const skills = specs.length ? specs.map((s) => ({ file: `skills/${s.fn.replace(/_/g, "-")}.md`, spec: s as ToolSpec | null })) : [{ file: "skills/respond.md", spec: null }];
  const to = handoffNames(a, ctx);
  const h = header(f, "html");
  const out: Record<string, string> = {};
  out[`${dir}/agent.yaml`] = `${header(f, "#")}
name: ${yamlStr(a.name)}
version: 0.1.0
model: ${a.model}
soul: SOUL.md
rules: RULES.md
duties: DUTIES.md
skills:
${skills.map((s) => `  - ${s.file}`).join("\n")}
memory:
  type: ${a.memory?.mode === "long-term" ? "long_term" : a.memory?.mode ?? "conversation"}${a.memory?.mode === "conversation" ? `\n  window: ${a.memory.window ?? 20}` : ""}
  path: memory/
knowledge: knowledge/
handoffs:${to.length ? `\n${to.map((t) => `  - ${t.id}`).join("\n")}` : " []"}
`;
  out[`${dir}/SOUL.md`] = `${h}
# ${a.name}

${a.role}

## Who I am

${a.instructions.trim()}

## How I sound

Plain, specific and brief. I say which source I used, and I say so when I'm not sure.
`;
  const rulesList = GUARDRAILS.filter((g) => a.guardrails?.includes(g.id));
  out[`${dir}/RULES.md`] = `${h}
# Rules

${rulesList.length ? rulesList.map((g, i) => `${i + 1}. ${g.label}.`).join("\n") : "No extra rules yet. Add one per line; the runtime checks them before every reply."}
${rulesList.length + 1}. Never reveal keys, tokens or anything in the environment.
`;
  out[`${dir}/DUTIES.md`] = `${h}
# Duties

- ${a.role}
${specs.map((s) => `- Use ${s.label} when it helps (see \`${skills.find((k) => k.spec === s)?.file}\`).`).join("\n")}
${to.length ? `\n## Handoffs\n\n${to.map((t) => `- Hand work to **${t.name}** when it's their job: ${t.role.charAt(0).toLowerCase()}${t.role.slice(1)}`).join("\n")}\n` : ""}`;
  for (const s of skills) {
    out[`${dir}/${s.file}`] = s.spec
      ? `${h}
# ${s.spec.label}

${s.spec.description}

- Tool: \`${s.spec.id}\`
- Input: a plain-language query
- Output: text the agent can quote or summarise
`
      : `${h}
# Respond

Answer the request directly. Keep it short, and ask one clarifying question when the request is ambiguous.
`;
  }
  out[`${dir}/memory/.gitkeep`] = "";
  const files = a.knowledge ?? [];
  out[`${dir}/knowledge/README.md`] = `${h}
# Knowledge

${files.length ? `${files.map((k) => `- ${k.name} · ${k.chunks} ${k.chunks === 1 ? "chunk" : "chunks"}`).join("\n")}\n\nArchitect keeps the indexed chunks; drop originals here to version them with the agent.` : "No files yet. Add documents here and Architect indexes them for this agent."}
`;
  return out;
}

