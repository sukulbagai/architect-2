/** The files one agent contributes to the project, keyed by path. */
export function agentFiles(agent: PlanAgent, ctx: Ctx): Record<string, string> {
  const a = withAgentDefaults(agent);
  const f = frameworkOf(a.framework);
  switch (f.id) {
    case "langgraph":
      return { [`agents/${a.id}.py`]: langgraph(a, f, ctx) };
    case "crewai":
      return { [`agents/${a.id}.py`]: crewai(a, f, ctx) };
    case "google-adk":
      return { [`agents/${a.id}/__init__.py`]: `${header(f, "#")}\nfrom . import agent\n`, [`agents/${a.id}/agent.py`]: googleAdk(a, f, ctx) };
    case "openai-agents":
      return { [`agents/${a.id}.ts`]: openaiAgents(a, f, ctx) };
    case "claude-agent-sdk":
      return { [`agents/${a.id}.ts`]: claudeAgentSdk(a, f, ctx) };
    case "mastra":
      return { [`src/mastra/agents/${a.id}.ts`]: mastra(a, f, ctx) };
    case "gitagent":
      return gitagent(a, f, ctx, `agents/${a.id}`);
    default:
      return { [`agents/${a.id}.yaml`]: lyzr(a, f) };
  }
}

/** The file that best represents an agent, for "Open in Code tab". */
export function agentEntry(agent: PlanAgent): string {
  const f = frameworkOf(agent.framework).id;
  const id = agent.id;
  const entries: Record<FrameworkId, string> = {
    lyzr: `agents/${id}.yaml`,
    langgraph: `agents/${id}.py`,
    crewai: `agents/${id}.py`,
    "google-adk": `agents/${id}/agent.py`,
    "openai-agents": `agents/${id}.ts`,
    "claude-agent-sdk": `agents/${id}.ts`,
    mastra: `src/mastra/agents/${id}.ts`,
    gitagent: `agents/${id}/SOUL.md`,
  };
  return entries[f];
}

/** Python and npm packages the plan's agent frameworks need. */
export function agentPackages(plan: Pick<Plan, "agents">) {
  const python = new Set<string>();
  const node = new Set<string>();
  for (const a of plan.agents) {
    const f = frameworkOf(a.framework);
    if (f.language === "Python") {
      f.packages.forEach((p) => python.add(p));
      python.add("httpx==0.28.1");
    } else if (f.language === "TypeScript") {
      f.packages.forEach((p) => node.add(p));
      if (f.id === "openai-agents") ["@openai/agents-extensions@^0.1.0", "@ai-sdk/anthropic@^2.0.0"].forEach((p) => node.add(p));
    }
  }
  return { python: [...python].sort(), node: [...node].sort() };
}
