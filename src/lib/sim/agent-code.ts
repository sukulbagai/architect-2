import { INTEGRATIONS } from "../integrations";
import { BUILTIN_TOOLS, GUARDRAILS, isHttpTool, isMcpTool, toolId, toolIntegration, toolLabel, withAgentDefaults } from "./agents";
import { frameworkOf, type Framework, type FrameworkId } from "./frameworks";
import type { Plan, PlanAgent } from "./types";

/**
 * Per-framework source for one agent. The code is plausible, readable source for each SDK as of
 * mid-2026; it's generated from the agent's config and never runs inside Architect. None of these
 * SDKs are Architect's own dependencies: they appear only in the generated project.
 */

type Ctx = Pick<Plan, "appName" | "agents">;

const snake = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "") || "agent";
const camel = (s: string) => snake(s).replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const upper = (s: string) => snake(s).toUpperCase();

function header(f: Framework, style: "//" | "#" | "html") {
  const text = `Generated by Architect · ${f.label} · edit freely`;
  return style === "html" ? `<!-- ${text} -->` : `${style} ${text}`;
}

/** A Python triple-quoted string body. */
const pyText = (s: string) => s.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"');
/** A JS template-literal body. */
const tsText = (s: string) => s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const indent = (s: string, n: number) => s.replace(/\n/g, `\n${" ".repeat(n)}`);
/** A YAML scalar, quoted only when it has to be. */
const yamlStr = (s: string) => (/^[\w][\w .,'()&/-]*$/.test(s) && !/:\s|\s#/.test(s) ? s : JSON.stringify(s));

type ToolSpec = { tool: string; id: string; fn: string; label: string; description: string; mcp: boolean; env?: string };

function toolSpecs(a: PlanAgent): ToolSpec[] {
  return a.tools.map((tool) => {
    const id = toolId(tool);
    const mcp = isMcpTool(tool);
    const label = toolLabel(tool);
    const builtin = BUILTIN_TOOLS.find((b) => b.name === tool);
    const integration = toolIntegration(tool) ?? INTEGRATIONS.find((i) => i.name === tool);
    const http = isHttpTool(tool);
    const description = builtin
      ? builtin.note
      : mcp
        ? `Tools from the ${label} MCP server.`
        : http
          ? `Calls the ${label} HTTP API with the headers saved in Architect.`
          : integration?.description ?? `Calls ${label}.`;
    const fn = mcp ? `${snake(label)}_mcp` : http ? `${snake(label)}_api` : snake(id);
    return { tool, id, fn, label, description, mcp, env: mcp ? `${upper(label)}_MCP_URL` : undefined };
  });
}

/** Guardrails as plain rules, appended to every framework's system prompt. */
function rules(a: PlanAgent) {
  const list = GUARDRAILS.filter((g) => a.guardrails?.includes(g.id)).map((g) => `- ${g.label}.`);
  return list.length ? `\n\nRules:\n${list.join("\n")}` : "";
}

function prompt(a: PlanAgent) {
  return `${a.instructions.trim()}${rules(a)}`;
}

function handoffNames(a: PlanAgent, ctx: Ctx) {
  return (a.handoffs ?? []).map((id) => ctx.agents.find((x) => x.id === id)).filter((x): x is PlanAgent => !!x);
}

function knowledgeNote(a: PlanAgent) {
  const files = a.knowledge ?? [];
  if (!files.length) return "";
  const chunks = files.reduce((s, f) => s + f.chunks, 0);
  return `Indexed by Architect: ${files.map((f) => f.name).join(", ")} (${chunks} ${chunks === 1 ? "chunk" : "chunks"}).`;
}

