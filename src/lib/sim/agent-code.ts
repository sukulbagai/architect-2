const PY_CALL_TOOL = `def call_tool(name: str, **args) -> str:
    """Tool calls go through the app's server, which holds each connection's keys."""
    response = httpx.post(f"{os.environ['ARCHITECT_TOOLS_URL']}/{name}", json=args, timeout=30)
    response.raise_for_status()
    return response.text`;

function pyToolFns(a: PlanAgent, specs: ToolSpec[], decorator: (s: ToolSpec) => string, returns: "str" | "dict") {
  return specs
    .map((s) => {
      const doc = s.id === "knowledge_base" && knowledgeNote(a) ? `${s.description} ${knowledgeNote(a)}` : s.description;
      const body = returns === "dict" ? `{"status": "success", "result": call_tool("${s.id}", query=query)}` : `call_tool("${s.id}", query=query)`;
      return `${decorator(s)}def ${s.fn}(query: str) -> ${returns}:
    """${pyText(doc)}"""
    return ${body}`;
    })
    .join("\n\n\n");
}

function pyHandoffs(a: PlanAgent, ctx: Ctx) {
  const to = handoffNames(a, ctx);
  if (!to.length) return "";
  return `\n\n# The Architect runtime routes handoffs, whichever framework the other agent uses.\nHANDOFFS = [${to.map((t) => `"${t.id}"`).join(", ")}]  # ${to.map((t) => t.name).join(", ")}`;
}

function langgraph(a: PlanAgent, f: Framework, ctx: Ctx) {
  const specs = toolSpecs(a);
  const State = `${camel(a.id).replace(/^./, (c) => c.toUpperCase())}State`;
  const memory = a.memory?.mode ?? "conversation";
  const imports = [
    "import os",
    "from typing import Annotated, TypedDict",
    "",
    "import httpx",
    "from langchain_anthropic import ChatAnthropic",
    "from langchain_core.messages import AnyMessage, HumanMessage, SystemMessage",
    ...(specs.length ? ["from langchain_core.tools import tool"] : []),
    ...(memory !== "off" ? ["from langgraph.checkpoint.memory import MemorySaver"] : []),
    "from langgraph.graph import END, StateGraph",
    "from langgraph.graph.message import add_messages",
    ...(specs.length ? ["from langgraph.prebuilt import ToolNode"] : []),
    ...(memory === "long-term" ? ["from langgraph.store.memory import InMemoryStore"] : []),
  ];
  const nodes = specs.map((s) => `graph.add_node("${s.fn}", ToolNode([${s.fn}]))`).join("\n");
  const routes = specs.map((s) => `"${s.fn}": "${s.fn}"`).join(", ");
  const compile =
    memory === "off" ? "graph.compile()" : memory === "long-term" ? "graph.compile(checkpointer=MemorySaver(), store=InMemoryStore())" : "graph.compile(checkpointer=MemorySaver())";
  return `${header(f, "#")}
"""${pyText(a.name)}: ${pyText(a.role)}"""
${imports.join("\n")}

SYSTEM_PROMPT = """${pyText(prompt(a))}"""${pyHandoffs(a, ctx)}


${PY_CALL_TOOL}


class ${State}(TypedDict):
    messages: Annotated[list[AnyMessage], add_messages]
${specs.length ? `\n\n${pyToolFns(a, specs, () => "@tool\n", "str")}\n\n\nTOOLS = [${specs.map((s) => s.fn).join(", ")}]\n` : ""}
model = ChatAnthropic(model="${a.model}", temperature=0)${specs.length ? ".bind_tools(TOOLS)" : ""}


def agent(state: ${State}) -> dict:
    reply = model.invoke([SystemMessage(SYSTEM_PROMPT), *state["messages"]])
    return {"messages": [reply]}
${
  specs.length
    ? `

def route(state: ${State}) -> str:
    last = state["messages"][-1]
    calls = getattr(last, "tool_calls", None)
    return calls[0]["name"] if calls else END
`
    : ""
}

graph = StateGraph(${State})
graph.add_node("agent", agent)
${specs.length ? `${nodes}\n` : ""}graph.set_entry_point("agent")
${
  specs.length
    ? `graph.add_conditional_edges("agent", route, {${routes}, END: END})\n${specs.map((s) => `graph.add_edge("${s.fn}", "agent")`).join("\n")}`
    : `graph.add_edge("agent", END)`
}

app = ${compile}


def run(text: str, thread_id: str = "default") -> str:
    result = app.invoke({"messages": [HumanMessage(text)]}${memory === "off" ? "" : ', config={"configurable": {"thread_id": thread_id}}'})
    return result["messages"][-1].content
`;
}

function crewai(a: PlanAgent, f: Framework, ctx: Ctx) {
  const specs = toolSpecs(a);
  const v = snake(a.id);
  const memory = (a.memory?.mode ?? "conversation") !== "off";
  return `${header(f, "#")}
"""${pyText(a.name)}: ${pyText(a.role)}"""
import os

import httpx
from crewai import Agent, Crew, Process, Task
${specs.length ? "from crewai.tools import tool\n" : ""}

${PY_CALL_TOOL}
${specs.length ? `\n\n${pyToolFns(a, specs, (s) => `@tool("${s.label}")\n`, "str")}\n` : ""}

${v} = Agent(
    role="${pyText(a.name)}",
    goal="${pyText(a.role)}",
    backstory="""${pyText(prompt(a))}""",
    tools=[${specs.map((s) => s.fn).join(", ")}],
    llm="anthropic/${a.model}",
    memory=${memory ? "True" : "False"},
    allow_delegation=${(a.handoffs ?? []).length ? "True" : "False"},
    verbose=False,
)

task = Task(
    description="{input}",
    expected_output="A short, specific answer${a.guardrails?.includes("cite-sources") ? " that cites its sources" : ""}.",
    agent=${v},
)

crew = Crew(agents=[${v}], tasks=[task], process=Process.sequential, memory=${memory ? "True" : "False"})${pyHandoffs(a, ctx)}


def run(text: str) -> str:
    return str(crew.kickoff(inputs={"input": text}))
`;
}

function googleAdk(a: PlanAgent, f: Framework, ctx: Ctx) {
  const specs = toolSpecs(a);
  return `${header(f, "#")}
"""${pyText(a.name)}: ${pyText(a.role)}"""
import os

import httpx
from google.adk.agents import Agent
from google.adk.models.lite_llm import LiteLlm


${PY_CALL_TOOL}
${specs.length ? `\n\n${pyToolFns(a, specs, () => "", "dict")}\n` : ""}

root_agent = Agent(
    name="${snake(a.id)}",
    model=LiteLlm(model="anthropic/${a.model}"),
    description="${pyText(a.role)}",
    instruction="""${pyText(prompt(a))}""",
    tools=[${specs.map((s) => s.fn).join(", ")}],
)${pyHandoffs(a, ctx)}
`;
}

