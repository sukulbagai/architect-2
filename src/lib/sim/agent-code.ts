const TS_CALL_TOOL = `/** Tool calls go through the app's server, which holds each connection's keys. */
async function callTool(name: string, args: Record<string, unknown>): Promise<string> {
  const res = await fetch(\`\${process.env.ARCHITECT_TOOLS_URL}/\${name}\`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(args),
  });
  if (!res.ok) throw new Error(\`\${name} failed: \${res.status}\`);
  return res.text();
}`;

function tsHandoffs(a: PlanAgent, ctx: Ctx) {
  const to = handoffNames(a, ctx);
  if (!to.length) return "";
  return `\n\n/** The Architect runtime routes handoffs, whichever framework the other agent uses. */\nexport const handoffs = [${to.map((t) => `"${t.id}"`).join(", ")}] as const;`;
}

function tsDescription(a: PlanAgent, s: ToolSpec) {
  return JSON.stringify(s.id === "knowledge_base" && knowledgeNote(a) ? `${s.description} ${knowledgeNote(a)}` : s.description);
}

function openaiAgents(a: PlanAgent, f: Framework, ctx: Ctx) {
  const specs = toolSpecs(a);
  const v = camel(a.id);
  const tools = specs
    .map(
      (s) => `const ${camel(s.fn)} = tool({
  name: "${s.fn}",
  description: ${tsDescription(a, s)},
  parameters: z.object({ query: z.string() }),
  execute: ({ query }) => callTool("${s.id}", { query }),
});`,
    )
    .join("\n\n");
  return `${header(f, "//")}
import { anthropic } from "@ai-sdk/anthropic";
import { Agent, run as runAgent${specs.length ? ", tool" : ""} } from "@openai/agents";
import { aisdk } from "@openai/agents-extensions";
${specs.length ? 'import { z } from "zod";\n' : ""}
${TS_CALL_TOOL}
${tools ? `\n${tools}\n` : ""}
/** ${a.name}: ${a.role} */
export const ${v} = new Agent({
  name: ${JSON.stringify(a.name)},
  instructions: \`${tsText(prompt(a))}\`,
  model: aisdk(anthropic("${a.model}")),
  tools: [${specs.map((s) => camel(s.fn)).join(", ")}],
});${tsHandoffs(a, ctx)}

export async function run(input: string): Promise<string> {
  const result = await runAgent(${v}, input);
  return String(result.finalOutput ?? "");
}
`;
}

function claudeAgentSdk(a: PlanAgent, f: Framework, ctx: Ctx) {
  const specs = toolSpecs(a);
  const custom = specs.filter((s) => !s.mcp && s.id !== "web_search");
  const mcp = specs.filter((s) => s.mcp);
  const server = `${snake(a.id).replace(/_/g, "-")}-tools`;
  const allowed = [
    ...(specs.some((s) => s.id === "web_search") ? ['"WebSearch"'] : []),
    ...custom.map((s) => `"mcp__${server}__${s.fn}"`),
    ...mcp.map((s) => `"mcp__${snake(s.label)}"`),
  ];
  const servers = [
    ...(custom.length ? [`"${server}": tools`] : []),
    ...mcp.map((s) => `${snake(s.label)}: { type: "http", url: process.env.${s.env}! }`),
  ];
  return `${header(f, "//")}
import { ${custom.length ? "createSdkMcpServer, " : ""}query${custom.length ? ", tool" : ""} } from "@anthropic-ai/claude-agent-sdk";
${custom.length ? 'import { z } from "zod";\n' : ""}
const SYSTEM_PROMPT = \`${tsText(prompt(a))}\`;
${
  custom.length
    ? `
${TS_CALL_TOOL}

const tools = createSdkMcpServer({
  name: "${server}",
  version: "1.0.0",
  tools: [
${custom
  .map(
    (s) => `    tool("${s.fn}", ${tsDescription(a, s)}, { query: z.string() }, async ({ query }) => ({
      content: [{ type: "text", text: await callTool("${s.id}", { query }) }],
    })),`,
  )
  .join("\n")}
  ],
});`
    : ""
}${tsHandoffs(a, ctx)}

/** Runs ${a.name} on one input and returns its final answer. */
export async function run(input: string): Promise<string> {
  let answer = "";
  for await (const message of query({
    prompt: input,
    options: {
      systemPrompt: SYSTEM_PROMPT,
      model: "${a.model}",
${servers.length ? `      mcpServers: { ${servers.join(", ")} },\n` : ""}      allowedTools: [${allowed.join(", ")}],
      maxTurns: 8,
    },
  })) {
    if (message.type === "result" && message.subtype === "success") answer = message.result;
  }
  return answer;
}
`;
}

function mastra(a: PlanAgent, f: Framework, ctx: Ctx) {
  const specs = toolSpecs(a);
  const v = `${camel(a.id)}Agent`;
  const memory = a.memory?.mode ?? "conversation";
  const tools = specs
    .map(
      (s) => `const ${camel(s.fn)} = createTool({
  id: "${s.fn}",
  description: ${tsDescription(a, s)},
  inputSchema: z.object({ query: z.string() }),
  execute: async ({ context }) => callTool("${s.id}", { query: context.query }),
});`,
    )
    .join("\n\n");
  const mem =
    memory === "off"
      ? ""
      : memory === "long-term"
        ? "\n  memory: new Memory({ options: { lastMessages: 20, semanticRecall: true, workingMemory: { enabled: true } } }),"
        : `\n  memory: new Memory({ options: { lastMessages: ${a.memory?.window ?? 20} } }),`;
  return `${header(f, "//")}
import { anthropic } from "@ai-sdk/anthropic";
import { Agent } from "@mastra/core/agent";
${specs.length ? 'import { createTool } from "@mastra/core/tools";\n' : ""}${memory !== "off" ? 'import { Memory } from "@mastra/memory";\n' : ""}${specs.length ? 'import { z } from "zod";\n' : ""}
${specs.length ? `${TS_CALL_TOOL}\n\n${tools}\n\n` : ""}/** ${a.name}: ${a.role} */
export const ${v} = new Agent({
  name: ${JSON.stringify(a.name)},
  instructions: \`${tsText(prompt(a))}\`,
  model: anthropic("${a.model}"),
  tools: { ${specs.map((s) => camel(s.fn)).join(", ")} },${mem}
});${tsHandoffs(a, ctx)}

export async function run(input: string): Promise<string> {
  const result = await ${v}.generate(input);
  return result.text;
}
`;
}

