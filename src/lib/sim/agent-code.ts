// Lyzr (YAML, hosted)
// ---------------------------------------------------------------------------------------------

function lyzr(a: PlanAgent, f: Framework) {
  const list = (items: string[]) => (items.length ? `\n${items.map((i) => `  - ${i}`).join("\n")}` : " []");
  const knowledge = (a.knowledge ?? []).map((k) => `${yamlStr(k.name)}  # ${k.chunks} ${k.chunks === 1 ? "chunk" : "chunks"}`);
  return `${header(f, "#")}
name: ${yamlStr(a.name)}
framework: lyzr
model: ${a.model}
role: ${yamlStr(a.role)}
instructions: |
  ${indent(a.instructions.trim(), 2)}
tools:${list(a.tools.map(toolId))}
knowledge:${list(knowledge)}
memory:
  type: ${a.memory?.mode === "long-term" ? "long_term" : a.memory?.mode ?? "conversation"}${a.memory?.mode === "conversation" ? `\n  window: ${a.memory.window ?? 20}` : ""}
guardrails:${list(GUARDRAILS.filter((g) => a.guardrails?.includes(g.id)).map((g) => g.code))}
handoffs:${list(a.handoffs ?? [])}
`;
}

